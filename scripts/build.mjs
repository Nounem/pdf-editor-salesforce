import { build } from 'esbuild';
import { mkdir, readFile, writeFile, stat, appendFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const directory = 'force-app/main/default/staticresources';
await mkdir(directory, { recursive: true });
await build({ absWorkingDir: process.cwd(), tsconfigRaw: {}, entryPoints: [resolve('scripts/engine-entry.js')], outfile: `${directory}/lovePdfEngine.resource`, bundle: true,
    inject: [resolve('scripts/pdf-message-clone.js')],
    format: 'iife', platform: 'browser', target: 'es2022', minify: true, keepNames: true, legalComments: 'inline' });
const size = (await stat(`${directory}/lovePdfEngine.resource`)).size;
if (size > 5000000) throw new Error(`Static Resource exceeds 5 MB: ${size}`);
await writeFile(`${directory}/lovePdfEngine.resource-meta.xml`, '<?xml version="1.0" encoding="UTF-8"?>\n<StaticResource xmlns="http://soap.sforce.com/2006/04/metadata"><cacheControl>Private</cacheControl><contentType>application/javascript</contentType><description>PDF.js and pdf-lib bundled locally. See THIRD_PARTY_NOTICES.md.</description></StaticResource>\n');
const pdfjsLicense = await readFile('node_modules/pdfjs-dist/LICENSE', 'utf8');
const pdfLibLicense = await readFile('node_modules/pdf-lib/LICENSE.md', 'utf8');
await writeFile('THIRD_PARTY_NOTICES.md', `# Third-party notices\n\nGenerated by npm run build.\n\n## PDF.js 6.4.299\n\n${pdfjsLicense}\n\n## pdf-lib 1.17.1\n\n${pdfLibLicense}\n`);
for (const [name, license] of [['@pdf-lib/standard-fonts', 'LICENSE.md'], ['@pdf-lib/upng', 'LICENSE'], ['pako', 'LICENSE'], ['@ungap/structured-clone', 'LICENSE']]) {
    const metadata = JSON.parse(await readFile(`node_modules/${name}/package.json`, 'utf8'));
    await appendFile('THIRD_PARTY_NOTICES.md', `\n## ${name} ${metadata.version}\n\n${await readFile(`node_modules/${name}/${license}`, 'utf8')}\n`);
}
console.log(`Built lovePdfEngine.resource: ${size} bytes`);
